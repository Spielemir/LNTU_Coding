x1 = float(input("Введіть x1: "))
y1 = float(input("Введіть y1: "))

x2 = float(input("Введіть x2: "))
y2 = float(input("Введіть y2: "))

dis = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5

print("Відстань між точками: ", dis)

if dis < 5:
    print("Точки близько одна до одної.")
elif dis == 5:
    print("Точки на відстані 5 одиниць одна від одної.")
else:
    print("Точки далеко одна від одної.")